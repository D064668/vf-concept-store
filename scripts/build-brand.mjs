// build-brand.mjs — turns the official SVG files in public/assets into React
// components that take their colour from CSS (currentColor), so the same logo
// works in light mode, dark mode and on photos. Run once: node scripts/build-brand.mjs
import fs from 'node:fs';
const read = (f) => fs.readFileSync(f, 'utf8');
const paths = (svg) => [...svg.matchAll(/<path([^>]*?)\/?>/g)].map((m) => m[1]
  .replace(/fill="#[0-9A-Fa-f]{6}"/, '')
  .replace(/fill-rule=/g, 'fillRule=').replace(/clip-rule=/g, 'clipRule=').trim());
const vb = (svg) => /viewBox="([^"]+)"/.exec(svg)[1];
const logo = read('public/assets/logos/S.Fashion_Logo_Black.svg');
const small = read('public/assets/logos/S.Fashion_Logo_Small_Black.svg');
const spark = read('public/assets/icons/S.Fashion_Sparkle_Black.svg');
const sp = paths(spark);
const out = `// GENERATED by scripts/build-brand.mjs from public/assets (official S·Fashion vectors).
// Colour comes from CSS \`color\` (currentColor). Decorative by default (aria-hidden).
import type { SVGProps } from 'react';

type P = SVGProps<SVGSVGElement> & { title?: string };
const a11y = (title?: string) => (title ? { role: 'img' as const, 'aria-label': title } : { 'aria-hidden': true as const });

/** Line-S logo. Use at 32px tall and up (D6). Ratio 1052 : 185 */
export function LogoLine({ title, ...p }: P) {
  return (
    <svg viewBox="${vb(logo)}" fill="currentColor" {...a11y(title)} {...p}>
      ${paths(logo).map((d) => `<path ${d} />`).join('\n      ')}
    </svg>
  );
}

/** Solid-S logo. Use under 32px tall, e.g. 16px in top bars (D6). Ratio 2253 : 388 */
export function LogoSolid({ title, ...p }: P) {
  return (
    <svg viewBox="${vb(small)}" fill="currentColor" {...a11y(title)} {...p}>
      ${paths(small).map((d) => `<path ${d} />`).join('\n      ')}
    </svg>
  );
}

/** The stylist's sparkle mark: the gem plus three small sparkles.
 *  Parts carry class names so CSS can float the gem and twinkle the sparkles. */
export function Sparkle({ title, ...p }: P) {
  return (
    <svg viewBox="${vb(spark)}" fill="currentColor" {...a11y(title)} {...p}>
      <path className="sf-gem" ${sp[0]} />
      ${sp.slice(1).map((d, i) => `<path className="sf-twinkle sf-twinkle-${i + 1}" ${d} />`).join('\n      ')}
    </svg>
  );
}
`;
fs.writeFileSync('src/components/brand.tsx', out);
console.log('brand.tsx written', sp.length, 'sparkle parts');
