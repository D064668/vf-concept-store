// build-tokens.mjs
// ------------------------------------------------------------------
// WHAT THIS DOES (plain English):
// Reads the design system file (design-system/tokens.json) and writes
// two "translations" of it, so web and iOS always use the same values:
//   1. src/styles/tokens.css  -> CSS variables for the web prototype
//   2. ios/SFTokens.swift     -> the same values for the iOS developer
// Run it with:  npm run tokens   (it also runs before dev / build)
//
// The app-level overrides at the bottom (APP) come from HANDOFF.md §4.
// They win over tokens.json because the approved mockups changed a few
// things after the design system was written (warm stone canvas, glass,
// soft shadows). Change a value here, re-run, and both outputs update.
// ------------------------------------------------------------------
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const src = JSON.parse(fs.readFileSync(path.join(root, 'design-system/tokens.json'), 'utf8'));

// ---------- 1. Read colour tokens into { name: {light, dark} } ----------
const raw = {};
for (const t of src.color.tokens) {
  raw[t.name] = typeof t.value === 'string' ? { light: t.value, dark: t.value } : { ...t.value };
}

// ---------- 2. App overrides (HANDOFF.md §4.1, "Soft Studio" look) ----------
const APP = {
  canvas: { light: '#F6F5F2', dark: '#121614' }, // warm stone (D8)
  'backdrop-top': { light: '#F8F7F4', dark: '#151A17' },
  'backdrop-bottom': { light: '#E9E6E0', dark: '#0F1311' },
  tile: { light: '#EEECE7', dark: '#1F2521' }, // product photo tile
  'focus-ring': { light: '{sage-700}', dark: '{sage-300}' },
  'shadow-c': { light: '{sage-900}', dark: '#000000' },
  scrim: { light: '{sage-900}', dark: '#000000' },
  'on-photo': { light: '#FFFFFF', dark: '#FFFFFF' },
  // product colours used by the placeholder catalogue (HANDOFF §4.1)
  'garment-sage': { light: '{sage-500}', dark: '{sage-500}' },
  'garment-ecru': { light: '#E7DFCB', dark: '#E7DFCB' },
  'garment-obsidian': { light: '#2B2E2C', dark: '#2B2E2C' },
  'garment-stone': { light: '#C9CCC7', dark: '#C9CCC7' },
  'garment-forest': { light: '{sage-900}', dark: '{sage-900}' },
  'garment-soft-sage': { light: '{sage-300}', dark: '{sage-300}' },
  'garment-sage-700': { light: '{sage-700}', dark: '{sage-700}' },
  // embroidery threads (HANDOFF §4.1, Personalise)
  'thread-gold': { light: '#C4AF7E', dark: '#C4AF7E' },
  'thread-ecru': { light: '#E7DFCB', dark: '#E7DFCB' },
  'thread-forest': { light: '#2D4A3E', dark: '#2D4A3E' },
  'thread-obsidian': { light: '#1F2120', dark: '#1F2120' },
};
Object.assign(raw, APP);

// ---------- 3. Resolve {references} like "{sage-700}" ----------
function resolve(value, mode, depth = 0) {
  const m = /^\{(.+)\}$/.exec(value);
  if (!m) return value;
  if (depth > 8) throw new Error('token loop at ' + value);
  const ref = raw[m[1]];
  if (!ref) throw new Error('unknown token ' + value);
  return resolve(ref[mode], mode, depth + 1);
}
const colors = {};
for (const [name, v] of Object.entries(raw)) {
  colors[name] = { light: resolve(v.light, 'light'), dark: resolve(v.dark ?? v.light, 'dark') };
}

// ---------- 4. Non-colour tokens ----------
const list = (group) => Object.fromEntries(group.tokens.map((t) => [t.name, t.value]));
const spacing = list(src.spacing);
const radius = list(src.radius);
const size = { ...list(src.size), 'button-height': '56px', 'chip-height': '38px', 'tabbar-height': '68px' };
const duration = list(src.duration);
const easing = list(src.easing);
const distance = list(src.distance);
const stagger = list(src.stagger);

// Type styles. HANDOFF §4.2: headings 700, Light (300) only at 20px+,
// eyebrows 700 12/16 +0.06em. Family falls back from SAP 72 to Poppins.
const typeStyles = {};
for (const g of src.type.groups) for (const s of g.styles) typeStyles[s.name] = s;

// ---------- 5. Write CSS ----------
const cssVar = (k, v) => `  --${k}: ${v};`;
const lightLines = Object.entries(colors).map(([k, v]) => cssVar(k, v.light));
const darkLines = Object.entries(colors)
  .filter(([, v]) => v.light !== v.dark)
  .map(([k, v]) => cssVar(k, v.dark));

const scalarLines = [
  ...Object.entries(spacing).map(([k, v]) => cssVar(k, v)),
  ...Object.entries(radius).map(([k, v]) => cssVar(k, v)),
  ...Object.entries(size).map(([k, v]) => cssVar(k, v)),
  ...Object.entries(duration).map(([k, v]) => cssVar(k, v)),
  ...Object.entries(easing).map(([k, v]) => cssVar(k, v)),
  ...Object.entries(distance).map(([k, v]) => cssVar(k, v)),
  ...Object.entries(stagger).map(([k, v]) => cssVar(k, v)),
];
const typeLines = Object.entries(typeStyles).map(
  ([k, s]) => `  --type-${k}: ${s.fontWeight} ${s.fontSize}/${s.lineHeight} var(--font-brand);`
);

const css = `/* GENERATED by scripts/build-tokens.mjs from design-system/tokens.json.
   Do not edit by hand: change the JSON or the APP overrides, then run \`npm run tokens\`. */

:root {
${lightLines.join('\n')}

  /* Composite tokens (built from the colours above) */
  --glass-bg: color-mix(in oklab, var(--surface) 62%, transparent);
  --glass-filter: blur(18px) saturate(1.2);
  --sheet-bg: color-mix(in oklab, var(--surface) 84%, transparent);
  --sheet-filter: blur(26px) saturate(1.15);
  /* bars over scrolling content: see-through, strongly blurred (iOS-style material) */
  --bar-bg: color-mix(in oklab, var(--canvas) 52%, transparent);
  --bar-filter: blur(20px) saturate(1.8);
  --shadow-chip: 0 8px 18px -10px color-mix(in oklab, var(--shadow-c) 45%, transparent);
  --shadow-soft: 0 18px 40px -18px color-mix(in oklab, var(--shadow-c) 50%, transparent);
  --shadow-bar: 0 18px 40px -14px color-mix(in oklab, var(--shadow-c) 45%, transparent);
  --shadow-primary: 0 16px 30px -16px color-mix(in oklab, var(--primary) 80%, transparent);

  /* Spacing, radius, size, motion */
${scalarLines.join('\n')}

  /* Type: SAP "72" when licensed, Poppins stand-in (HANDOFF §4.2) */
  --font-brand: "72", "72full", var(--font-poppins), "Poppins", Arial, Helvetica, sans-serif;
  --font-monogram: var(--font-archivo-narrow), "Archivo Narrow", "Arial Narrow", Arial, sans-serif;
${typeLines.join('\n')}

  color-scheme: light;
}

/* Dark theme: set data-theme="dark" on <html>, or follow the phone setting */
:root[data-theme="dark"] {
${darkLines.join('\n')}
  --glass-bg: color-mix(in oklab, var(--surface) 72%, transparent);
  --sheet-bg: color-mix(in oklab, var(--surface) 90%, transparent);
  --bar-bg: color-mix(in oklab, var(--canvas) 60%, transparent);
  color-scheme: dark;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${darkLines.map((l) => '  ' + l).join('\n')}
    --glass-bg: color-mix(in oklab, var(--surface) 72%, transparent);
    --sheet-bg: color-mix(in oklab, var(--surface) 90%, transparent);
    --bar-bg: color-mix(in oklab, var(--canvas) 60%, transparent);
    color-scheme: dark;
  }
}
`;
fs.mkdirSync(path.join(root, 'src/styles'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/styles/tokens.css'), css);

// ---------- 6. Write Swift for the iOS developer ----------
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const hexToRGB = (hex) => {
  const h = hex.replace('#', '');
  return [0, 2, 4].map((i) => (parseInt(h.slice(i, i + 2), 16) / 255).toFixed(4));
};
const swiftColors = Object.entries(colors)
  .filter(([, v]) => /^#[0-9a-f]{6}$/i.test(v.light) && /^#[0-9a-f]{6}$/i.test(v.dark))
  .map(([k, v]) => {
    const [lr, lg, lb] = hexToRGB(v.light);
    const [dr, dg, db] = hexToRGB(v.dark);
    return `    /// ${k}: light ${v.light} · dark ${v.dark}\n    static let ${camel(k)} = Color.sf(light: (${lr}, ${lg}, ${lb}), dark: (${dr}, ${dg}, ${db}))`;
  });
const px = (v) => parseFloat(v);
const swiftNums = (obj) =>
  Object.entries(obj)
    .filter(([, v]) => /px$/.test(v))
    .map(([k, v]) => `    static let ${camel(k)}: CGFloat = ${px(v)}`)
    .join('\n');
const swiftDur = Object.entries(duration)
  .map(([k, v]) => `    static let ${camel(k.replace('duration-', ''))}: Double = ${px(v) / 1000}`)
  .join('\n');
const swiftType = Object.entries(typeStyles)
  .map(
    ([k, s]) =>
      `    static let ${camel(k)} = SFTextStyle(size: ${px(s.fontSize)}, lineHeight: ${px(s.lineHeight)}, weight: ${
        { 300: '.light', 400: '.regular', 500: '.medium', 600: '.semibold', 700: '.bold' }[s.fontWeight]
      }, tracking: ${s.letterSpacing ? parseFloat(s.letterSpacing) : 0})`
  )
  .join('\n');

const swift = `// GENERATED by scripts/build-tokens.mjs from design-system/tokens.json.
// Same values as src/styles/tokens.css. Do not edit by hand.
import SwiftUI

extension Color {
    /// Builds a colour that switches automatically between light and dark mode.
    static func sf(light: (Double, Double, Double), dark: (Double, Double, Double)) -> Color {
        Color(UIColor { trait in
            let c = trait.userInterfaceStyle == .dark ? dark : light
            return UIColor(red: c.0, green: c.1, blue: c.2, alpha: 1)
        })
    }
}

enum SFColor {
${swiftColors.join('\n')}
}

enum SFSpace {
${swiftNums(spacing)}
}

enum SFRadius {
${swiftNums(radius)}
}

enum SFSize {
${swiftNums(size)}
}

enum SFDuration {
${swiftDur}
}

/// ease-brand cubic-bezier(0.22, 1, 0.36, 1) and ease-exit cubic-bezier(0.4, 0, 1, 1)
extension Animation {
    static func sfBrand(_ d: Double = SFDuration.standard) -> Animation { .timingCurve(0.22, 1, 0.36, 1, duration: d) }
    static func sfExit(_ d: Double = SFDuration.quick) -> Animation { .timingCurve(0.4, 0, 1, 1, duration: d) }
}

struct SFTextStyle {
    let size: CGFloat; let lineHeight: CGFloat; let weight: Font.Weight; let tracking: CGFloat
    /// Uses SAP 72 when bundled, else Poppins.
    var font: Font { .custom("Poppins", size: size).weight(weight) }
}

enum SFType {
${swiftType}
}
`;
fs.mkdirSync(path.join(root, 'ios'), { recursive: true });
fs.writeFileSync(path.join(root, 'ios/SFTokens.swift'), swift);

console.log(`tokens: ${Object.keys(colors).length} colours, ${Object.keys(typeStyles).length} type styles -> src/styles/tokens.css, ios/SFTokens.swift`);
