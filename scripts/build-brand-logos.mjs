// build-brand-logos.mjs — turns the brand logo SVGs in public/brands into one
// React component, <BrandLogo id="vans" />, coloured by CSS (currentColor) so
// each logo works in light mode, dark mode and on photos. Run: node scripts/build-brand-logos.mjs
import fs from 'node:fs';
const dir = 'public/brands';
const out = {};
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.svg'))) {
  const svg = fs.readFileSync(`${dir}/${f}`, 'utf8');
  const viewBox = /viewBox="([^"]+)"/.exec(svg)[1];
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/fill="(white|#fff|#ffffff|#FFF|#FFFFFF)"/g, 'fill="currentColor"')
    .replace(/\s+/g, ' ')
    .trim();
  out[f.replace('.svg', '')] = { viewBox, inner };
}
const ts = `// GENERATED by scripts/build-brand-logos.mjs from public/brands/*.svg — do not edit.
// Brand logos as one component. Colour follows CSS \`color\`.
import type { SVGProps } from 'react';

const LOGOS: Record<string, { viewBox: string; inner: string }> = ${JSON.stringify(out, null, 2)};

export type BrandId = ${Object.keys(out).map((k) => `'${k}'`).join(' | ')};

export function BrandLogo({ id, title, style, ...p }: { id: BrandId; title?: string } & SVGProps<SVGSVGElement>) {
  const l = LOGOS[id];
  const [, , w, h] = l.viewBox.split(' ').map(Number);
  return (
    <svg
      viewBox={l.viewBox}
      fill="none"
      // --logo-k evens out the logos optically: wide wordmarks get a little
      // shorter, stacked marks (like The North Face) a little taller.
      // Use it in CSS as  height: calc(20px * var(--logo-k))
      style={{ aspectRatio: \`\${w} / \${h}\`, ['--logo-k' as string]: (2 / Math.sqrt(w / h)).toFixed(3), ...style }}
      {...(title ? { role: 'img', 'aria-label': title } : { 'aria-hidden': true })}
      {...p}
      dangerouslySetInnerHTML={{ __html: l.inner }}
    />
  );
}
`;
fs.writeFileSync('src/components/BrandLogo.tsx', ts);
console.log('logos:', Object.keys(out).join(', '));
